#!/usr/bin/env python3
"""
Generate rsp/aspMain.toml for N64Recomp's RSPRecomp from the retail ROM, and
optionally run RSPRecomp to produce rsp/aspMain.cpp (the recompiled audio
microcode). Both files are generated at cmake configure time and are not
committed to the repository.

The game's audio tasks (OSTask type 2, logged as `[RSP]` by src/main.cpp) use:
  text  VRAM 0x80094260, task ucode_size 0x1000 -> ROM 0x94E60
  data  VRAM 0x800B4080, size 0x2DF             -> ROM 0xB4C80
Unlike libultra's aspMain (loaded at IMEM 0x04001080 behind rspboot), this
microcode is linked for IMEM 0x04001000: with 0x1080 its absolute jumps land
mid-routine (`jal 0x10C0` into a wait loop, `j 0x1054` into the boot area);
with 0x1000 they hit routine starts and the command loop, and the task's
ucode_size 0x1000 spans exactly IMEM 0x1000-0x2000. Trailing zero words are
trimmed. The tail of the text is a data table that decodes as INVALID
instructions and branches to non-existent labels; those gotos are patched to
a logged UnhandledJumpTarget return after RSPRecomp runs (never executed).

The microcode dispatches audio commands through a jump table at the start of
its data segment (16-bit IMEM addresses). RSPRecomp cannot see those indirect
targets, so they go in `extra_indirect_branch_targets`.

Usage (inside nix-shell tools/recomp-shell.nix):
  python3 tools/gen_aspmain.py --rom data/yoshis_story.z64 \
      [--rsprecomp build-n64recomp/RSPRecomp]
"""

import argparse
import re
import struct
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TEXT_ROM, TEXT_SIZE = 0x94E60, 0x1000
DATA_ROM, DATA_SIZE = 0xB4C80, 0x2DF
IMEM_TEXT = 0x04001000
IMEM_END = 0x04002000


def load_rom(path):
    rom = bytearray(path.read_bytes())
    magic = rom[:4]
    if magic == b"\x80\x37\x12\x40":
        pass                                    # .z64, big endian
    elif magic == b"\x37\x80\x40\x12":          # .v64, byte-swapped halfwords
        rom[0::2], rom[1::2] = rom[1::2], rom[0::2]
    elif magic == b"\x40\x12\x37\x80":          # .n64, little-endian words
        for i in range(0, len(rom) - 3, 4):
            rom[i:i + 4] = rom[i:i + 4][::-1]
    else:
        sys.exit(f"error: {path} does not look like an N64 ROM (magic {magic.hex()})")
    return bytes(rom)


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--rom", type=Path, default=ROOT / "data" / "yoshis_story.z64")
    ap.add_argument("--rsprecomp", type=Path, help="run this RSPRecomp binary afterwards")
    args = ap.parse_args()

    rom = load_rom(args.rom)

    text = rom[TEXT_ROM:TEXT_ROM + min(TEXT_SIZE, IMEM_END - IMEM_TEXT)]
    size = len(text)
    while size >= 4 and text[size - 4:size] == b"\0\0\0\0":
        size -= 4
    if size == 0:
        sys.exit("error: audio microcode text is all zeros - wrong ROM offset?")

    # The table follows a few constants (0000 0001 0002 FFFF ...), so take the
    # longest run of halfwords that are word-aligned addresses inside the code.
    data = rom[DATA_ROM:DATA_ROM + DATA_SIZE]
    lo, hi = IMEM_TEXT & 0x1FFF, (IMEM_TEXT & 0x1FFF) + size
    targets, run, table_off = [], [], 0
    for off in range(0, len(data) - 1, 2):
        (h,) = struct.unpack_from(">H", data, off)
        if lo <= h < hi and not h & 3:
            run.append(h)
            if len(run) > len(targets):
                targets, table_off = list(run), off + 2 - 2 * len(run)
        else:
            run = []

    print(f"text: ROM 0x{TEXT_ROM:X}, 0x{size:X} bytes of code (IMEM 0x{IMEM_TEXT:08X})")
    print("data[0:0x40]: " + " ".join(f"{w:04X}" for w in struct.unpack_from(">32H", data, 0)))
    print(f"jump table at data+0x{table_off:X}: {len(targets)} entries: " + ", ".join(f"0x{t:04X}" for t in targets))
    if len(targets) < 8:
        print("warning: fewer than 8 jump-table entries found; check data[0:0x40] above",
              file=sys.stderr)

    rsp_dir = ROOT / "rsp"
    rsp_dir.mkdir(exist_ok=True)
    toml = rsp_dir / "aspMain.toml"
    rom_rel = Path("..") / args.rom.resolve().relative_to(ROOT) if args.rom.resolve().is_relative_to(ROOT) \
        else args.rom.resolve()
    toml.write_text(
        "# Generated by tools/gen_aspmain.py - audio microcode for RSPRecomp.\n"
        f"text_offset = 0x{TEXT_ROM:X}\n"
        f"text_size = 0x{size:X}\n"
        f"text_address = 0x{IMEM_TEXT:08X}\n"
        f'rom_file_path = "{rom_rel.as_posix()}"\n'
        'output_file_path = "aspMain.cpp"\n'
        'output_function_name = "aspMain"\n'
        "extra_indirect_branch_targets = [ "
        + ", ".join(f"0x{t:04X}" for t in targets) + " ]\n"
        "unsupported_instructions = [ ]\n")
    print(f"wrote {toml.relative_to(ROOT)}")

    if args.rsprecomp:
            # Pass the full path: RSPRecomp resolves rom/output paths against the
        # toml's directory and fails on an empty one.
        subprocess.run([str(args.rsprecomp.resolve()), str(toml)], cwd=ROOT, check=True)
        patch_undefined_labels(rsp_dir / "aspMain.cpp")
        print(f"wrote rsp/aspMain.cpp")


def patch_undefined_labels(cpp):
    """Replace gotos to labels RSPRecomp never emitted (data decoded as code)."""
    text = cpp.read_text()
    defined = set(re.findall(r"^(L_[0-9A-F]{4}):", text, re.M))
    missing = set()

    def repl(m):
        if m.group(1) in defined:
            return m.group(0)
        missing.add(m.group(1))
        return ('{ printf("aspMain: jump to undefined %s\\n"); '
                'return RspExitReason::UnhandledJumpTarget; }' % m.group(1))

    text = re.sub(r"goto (L_[0-9A-F]{4});", repl, text)
    cpp.write_text(text)
    if missing:
        print("patched gotos to undefined labels: " + ", ".join(sorted(missing)))


if __name__ == "__main__":
    main()
