#!/usr/bin/env python3
"""
Draw the app icon (a spotted egg, original artwork) and write:
  assets/icon.png      256x256, for the desktop entry (tools/install_desktop.sh)
  src/icon_data.h      64x64 RGBA, for SDL_SetWindowIcon
No dependencies beyond the standard library.
"""

import math
import struct
import zlib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SS = 4  # supersampling per axis

OUTLINE = (24, 74, 30)
SHELL = (250, 250, 244)
SHADE = (214, 222, 208)
SPOT = (58, 170, 64)
SPOT_DARK = (36, 128, 44)
SHINE = (255, 255, 255)

# Spots: (x, y, radius) in egg space (x in -1..1, y in -1..1, y down).
SPOTS = [(-0.38, -0.12, 0.24), (0.36, -0.30, 0.22), (0.30, 0.30, 0.26),
         (-0.32, 0.55, 0.22), (0.12, -0.80, 0.13), (0.28, 0.78, 0.13)]


def egg(x, y):
    """Implicit egg: < 1 inside. Narrower at the top (y = -1)."""
    a = 0.74 * (1.0 + 0.16 * y)
    return (x / a) ** 2 + y ** 2


def shade(x, y):
    f = egg(x, y)
    if f > 1.0:
        return None
    if f > 0.86:
        return OUTLINE
    for sx, sy, r in SPOTS:
        d = math.hypot(x - sx, y - sy)
        if d < r:
            return SPOT_DARK if d > r * 0.78 else SPOT
    # Highlight top-left, shade bottom-right.
    if math.hypot((x + 0.22) * 1.6, y + 0.58) < 0.16:
        return SHINE
    t = max(0.0, min(1.0, (x * 0.6 + y * 0.8 + 0.2)))
    return tuple(round(SHELL[i] + (SHADE[i] - SHELL[i]) * t * t) for i in range(3))


def render(size):
    px = bytearray()
    for j in range(size):
        for i in range(size):
            acc = [0, 0, 0, 0]
            for sj in range(SS):
                for si in range(SS):
                    x = ((i + (si + 0.5) / SS) / size) * 2.0 - 1.0
                    y = ((j + (sj + 0.5) / SS) / size) * 2.0 - 1.0
                    c = shade(x * 1.06, y * 1.06)
                    if c:
                        acc[0] += c[0]; acc[1] += c[1]; acc[2] += c[2]; acc[3] += 255
            n = SS * SS
            a = acc[3] // n
            if a:
                cov = acc[3] / 255
                px += bytes((round(acc[0] / cov), round(acc[1] / cov), round(acc[2] / cov), a))
            else:
                px += b"\0\0\0\0"
    return bytes(px)


def write_png(path, size, rgba):
    raw = b"".join(b"\0" + rgba[y * size * 4:(y + 1) * size * 4] for y in range(size))
    def chunk(t, d):
        return struct.pack(">I", len(d)) + t + d + struct.pack(">I", zlib.crc32(t + d) & 0xFFFFFFFF)
    path.write_bytes(b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", struct.pack(">IIBBBBB", size, size, 8, 6, 0, 0, 0))
                     + chunk(b"IDAT", zlib.compress(raw, 9)) + chunk(b"IEND", b""))


def main():
    (ROOT / "assets").mkdir(exist_ok=True)
    write_png(ROOT / "assets" / "icon.png", 256, render(256))
    small = render(64)
    lines = [", ".join(f"0x{b:02X}" for b in small[i:i + 16]) for i in range(0, len(small), 16)]
    (ROOT / "src" / "icon_data.h").write_text(
        "// Generated by tools/gen_icon.py - 64x64 RGBA window icon.\n#pragma once\n#include <cstdint>\n"
        "static constexpr int kIconSize = 64;\nstatic const uint8_t kIconRGBA[64 * 64 * 4] = {\n    "
        + ",\n    ".join(lines) + "\n};\n")
    print("wrote assets/icon.png and src/icon_data.h")


if __name__ == "__main__":
    main()
