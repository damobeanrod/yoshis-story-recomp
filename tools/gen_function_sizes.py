#!/usr/bin/env python3
"""
Compute size overrides for size-0 FUNC symbols in the yoshi's story ELF.

Functions still in asm in the decomp are emitted with size=0, which
N64Recomp interprets as 0 instructions -> empty stub. Here we deduce each
one's real size as (next_symbol_address - this_symbol_address) within the
same section, so N64Recomp emits a real function body.

Run tools/check_elf_matches.py on the ELF first: sizes derived from a
non-matching ELF are self-consistent but the recomp will not line up with
the ROM data loaded at runtime.

Rules:
- Only override size-0 FUNC entries (don't touch declared sizes).
- If multiple symbols share the same VRAM, skip overriding the func_XXXXXXXX
  one when a real-named sibling (not matching ^func_[0-9A-F]{8}$) exists at
  that VRAM: the real symbol already produces the body, duplicating would
  emit two copies of the same instructions.
- Clip at the next FUNC symbol's address (regardless of its own size); a
  size that overlaps the next function would corrupt its disassembly.
- Only functions in code sections matching --sections are considered:
  .main plus every relocatable overlay section (.ovl_XXXXXX). Each section is
  sized independently and its last function runs to the end of the section's
  code. An .ovl_ section holds text + data + rodata + the relocation block, so
  its code ends at vramStart + textSize from the overlay's own relocation
  header (last word = offset back to {textSize, dataSize, rodataSize, ...}).
  Running to the section end instead swallowed each overlay's data, which
  decodes as INVALID, so tools/find_invalid_funcs.py / regen.py stubbed the
  last function of nearly every overlay (302 of them, incl. actor state
  setters like func_8047139C).

Usage:
  tools/gen_function_sizes.py --elf ../yoshis-story-matching/build/yoshisstory-us.elf \
                              --config config.toml
Without --config the TOML array is written to stdout.
"""

import argparse
import re
import struct
import subprocess
import sys
from pathlib import Path

GENERIC_NAME = re.compile(r"^func_[0-9A-Fa-f]{8}$")
BEGIN_MARKER = "# AUTO-GENERATED by tools/gen_function_sizes.py"


def code_sections(readelf, elf, pattern):
    """Return {readelf index: (name, addr, offset, size)} for sections matching pattern."""
    out = subprocess.check_output([readelf, "-SW", str(elf)], text=True, errors="replace")
    found = {}
    for line in out.splitlines():
        m = re.match(r"\s*\[\s*(\d+)\]\s+(\S+)\s+\S+\s+([0-9a-fA-F]+)\s+([0-9a-fA-F]+)\s+([0-9a-fA-F]+)", line)
        if m and re.fullmatch(pattern, m.group(2)):
            found[m.group(1)] = (m.group(2), int(m.group(3), 16), int(m.group(4), 16),
                                 int(m.group(5), 16))
    if not found:
        sys.exit(f"error: no section matching {pattern!r} in {elf}")
    return found


def code_end(elf_bytes, name, addr, offset, size):
    """VRAM where the section's code ends: textSize from an overlay's
    relocation header, or the section end for .main."""
    if not name.startswith(".ovl_"):
        return addr + size
    sec = elf_bytes[offset:offset + size]
    back = struct.unpack_from(">I", sec, size - 4)[0] if size >= 0x18 else 0
    hdr = size - back
    if back >= 0x18 and 0 <= hdr < size and not hdr & 3:
        text, data, rodata = struct.unpack_from(">3I", sec, hdr)
        if text + data + rodata == hdr and 0 < text <= hdr:
            return addr + text
    sys.exit(f"error: {name}: no valid overlay relocation header at the section end")


def dump_funcs(readelf, elf, section_indices):
    """Return {section index: [(vram, size, name), ...]} for FUNC symbols.

    Filters out `.L*` local labels — the yoshi decomp emits them as FUNC-typed
    symbols for branch targets inside bigger functions. Treating them as
    boundaries fractures the real enclosing function and produces broken
    inter-function branches at recompile time.
    """
    out = subprocess.check_output([readelf, "-sW", str(elf)], text=True, errors="replace")
    funcs = {idx: [] for idx in section_indices}
    for line in out.splitlines():
        parts = line.split()
        # Expect: Num:  Value  Size Type Bind Vis Ndx Name
        if len(parts) < 8:
            continue
        if parts[3] != "FUNC":
            continue
        if parts[6] not in funcs:
            continue
        try:
            vram = int(parts[1], 16)
            size = int(parts[2])
        except ValueError:
            continue
        name = parts[7]
        if name.startswith(".L"):
            continue  # local label, not a function entry
        funcs[parts[6]].append((vram, size, name))
    return funcs


def compute_overrides(funcs, section_end):
    # Group by vram so we can detect "generic + named" collisions.
    by_vram = {}
    for v, s, n in funcs:
        by_vram.setdefault(v, []).append((s, n))

    # Build the list of all VRAMs sorted; next-vram = clip boundary.
    vrams = sorted(by_vram.keys())

    overrides = []
    for i, v in enumerate(vrams):
        entries = by_vram[v]
        has_real_named = any(not GENERIC_NAME.match(n) for _, n in entries)
        has_sized = any(s > 0 for s, _ in entries)

        for s, n in entries:
            if s != 0:
                continue  # already sized; don't touch
            if GENERIC_NAME.match(n) and has_real_named:
                # Named sibling will provide the body (or already has one).
                continue
            if GENERIC_NAME.match(n) and has_sized:
                # Some other symbol at same VRAM is already sized.
                continue
            # Use next-vram boundary. A jr-last heuristic breaks functions
            # with forward branches past their last `jr` (Duff's device, loop
            # unrolling). Over-sizing is usually safe — the decoded tail runs
            # after `jr` so it never executes.
            # The last function in a section runs to the section's end.
            if i + 1 >= len(vrams):
                size = section_end - v
            else:
                size = vrams[i + 1] - v
            if size <= 0 or size & 3:
                sys.stderr.write(f"skip {n} @ 0x{v:08x}: computed size {size} invalid\n")
                continue
            overrides.append((n, size, v))
    return overrides


def render(overrides):
    lines = [
        BEGIN_MARKER + " — do not hand-edit.",
        f"# {len(overrides)} size-0 symbols sized to next-symbol boundary.",
        "function_sizes = [",
    ]
    for n, s, v in overrides:
        lines.append(f'    {{ name = "{n}", size = {s} }},  # @ 0x{v:08x}')
    lines.append("]")
    return "\n".join(lines) + "\n"


def splice_into_config(config, block):
    """Replace the generated block (BEGIN_MARKER through the closing `]`)."""
    text = config.read_text().splitlines(keepends=True)
    start = next((i for i, l in enumerate(text) if l.startswith(BEGIN_MARKER)), None)
    if start is None:
        sys.exit(f"error: {config} has no '{BEGIN_MARKER}' block to replace")
    end = next(i for i in range(start, len(text)) if text[i].rstrip() == "]")
    config.write_text("".join(text[:start]) + block + "".join(text[end + 1:]))


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--elf", required=True, type=Path)
    ap.add_argument("--readelf", default="readelf",
                    help="readelf binary (host readelf handles MIPS ELFs)")
    ap.add_argument("--sections", default=r"\.main|\.ovl_[0-9A-F]+",
                    help="regex of code section names to size (default: .main and all overlays)")
    ap.add_argument("--config", type=Path,
                    help="rewrite the generated function_sizes block in this TOML in place")
    args = ap.parse_args()

    sections = code_sections(args.readelf, args.elf, args.sections)
    funcs = dump_funcs(args.readelf, args.elf, sections.keys())
    elf_bytes = args.elf.read_bytes()
    overrides = []
    for idx, (name, addr, offset, size) in sorted(sections.items(), key=lambda kv: kv[1][1]):
        overrides += compute_overrides(funcs[idx], code_end(elf_bytes, name, addr, offset, size))
    block = render(overrides)
    if args.config:
        splice_into_config(args.config, block)
        print(f"wrote {len(overrides)} size overrides to {args.config}")
    else:
        sys.stdout.write(block)


if __name__ == "__main__":
    main()
